// ========== 聚合与查询 ==========

/** 三个阶段：基础巩固 / 核心突破 / 冲刺难词 */
export const GRADUATE_UNITS: GraduateUnit[][] = [
  GRADUATE_STAGE_1,
  GRADUATE_STAGE_2,
  GRADUATE_STAGE_3,
];

/**
 * 释义查表。
 * 词表自带释义，意味着这些词进单词本时直接有中文，
 * 不必再为它们调 /api/enrich-words。
 */
const MEANING_INDEX: Map<string, string> = (() => {
  const map = new Map<string, string>();
  for (const stage of GRADUATE_UNITS) {
    for (const unit of stage) {
      for (const word of unit.words) {
        const key = word.w.toLowerCase();
        if (!map.has(key)) map.set(key, word.m);
      }
    }
  }
  return map;
})();

export function getGraduateMeaning(word: string): string | undefined {
  return MEANING_INDEX.get(word.trim().toLowerCase());
}

/** 去重后的全部词条 */
export function getAllGraduateWords(): string[] {
  return [...MEANING_INDEX.keys()];
}

/**
 * 摸底取样用的难度分层。
 *
 * 三个阶段本身就是难度梯度。这比拿 WORD_POOL.college 那种人文社科研讨词
 * （subaltern / syllogism / postmodernism）靠谱得多——那些词考研根本不考，
 * 考研学生会全标「不认识」，词汇量被严重低估，还会被塞进第一篇文章。
 */
export function getGraduateTiers(): {
  basic: string[];
  core: string[];
  advanced: string[];
} {
  return {
    basic: GRADUATE_STAGE_1.flatMap((u) => u.words.map((w) => w.w)),
    core: GRADUATE_STAGE_2.flatMap((u) => u.words.map((w) => w.w)),
    advanced: GRADUATE_STAGE_3.flatMap((u) => u.words.map((w) => w.w)),
  };
}
